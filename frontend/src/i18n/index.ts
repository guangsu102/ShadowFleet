// ─────────────────────────────────────────────────────────────────────────────
// Translation engine (runtime)
// ─────────────────────────────────────────────────────────────────────────────

type Translator = (key: string, params?: Record<string, string | number>) => string

const translations: Record<Locale, Messages> = {
  en: enMessages,
  zh: zhMessages,
}

let _locale: Locale = 'en'
let _changeCallbacks: Array<(locale: Locale) => void> = []

export const currentLocale = (): Locale => _locale

export const setLocale = (locale: Locale): void => {
  if (_locale === locale) return
  _locale = locale
  _changeCallbacks.forEach((cb) => cb(locale))
}

export const onLocaleChange = (cb: (locale: Locale) => void): () => void => {
  _changeCallbacks.push(cb)
  return () => {
    _changeCallbacks = _changeCallbacks.filter((fn) => fn !== cb)
  }
}

export const t: Translator = (key: string, params?: Record<string, string | number>): string => {
  const parts = key.split('.')
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  let value: any = translations[_locale]
  for (const part of parts) {
    if (value == null || typeof value !== 'object') return key
    value = value[part]
  }
  if (typeof value !== 'string') return key
  if (!params) return value
  return value.replace(/\{\{(\w+)\}\}/g, (_, k) => String(params[k] ?? `{${k}}`))
}
